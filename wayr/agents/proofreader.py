"""Proofreader Agent - Reviews and edits articles."""

import re
from typing import List
from datetime import datetime, timezone
from wayr.agents.base import BaseAgent
from wayr.models import GeneratedArticle, EditedArticle
from wayr.utils import get_logger

logger = get_logger(__name__)

SYSTEM_PROMPT = "You are a professional editor for a tech news publication. Your three missions: fix errors, remove bias, and preserve citations. Respond only with valid JSON."


class ProofreaderAgent(BaseAgent):
    """Agent responsible for proofreading and editing AI-generated articles."""

    def __init__(
        self,
        api_key: str,
        model: str,
        provider: str = "anthropic",
        temperature: float = 0.3,
        max_tokens: int = 2000,
        target_words: int = 800,
    ):
        super().__init__(
            name="ProofreaderAgent",
            provider=provider,
            model=model,
            api_key=api_key,
            temperature=temperature,
            max_tokens=max_tokens,
        )
        self.target_words = target_words

    async def proofread_articles(
        self, generated_articles: List[GeneratedArticle]
    ) -> List[EditedArticle]:
        """Proofread and edit generated articles."""
        logger.info(f"Proofreading {len(generated_articles)} articles...")

        edited = []
        for generated in generated_articles:
            try:
                result = await self._proofread_single(generated)
                if result:
                    edited.append(result)
            except Exception as e:
                logger.error(
                    f"Error proofreading article '{generated.generated_title}': {e}"
                )
                # On error, create a pass-through EditedArticle with no changes
                edited.append(
                    EditedArticle(
                        generated=generated,
                        edited_title=generated.generated_title,
                        edited_content=generated.generated_content,
                        edit_summary=f"Proofreading skipped due to error: {str(e)}",
                        editor_model=self.model,
                    )
                )
                continue

        logger.info(f"Successfully proofread {len(edited)} articles")
        return edited

    async def _proofread_single(self, generated: GeneratedArticle) -> EditedArticle:
        """Proofread a single article."""
        original_title = generated.generated_title
        original_content = generated.generated_content

        # Get original source info for context
        original_article = generated.classified.original
        categories_str = ", ".join(generated.classified.categories) or "Uncategorized"

        # Get original RSS tags for category validation
        original_tags = original_article.tags if original_article.tags else []
        tags_str = ", ".join(original_tags) if original_tags else "None"

        prompt = f"""You are a professional editor for a tech news publication. Your task is to proofread and improve this AI-generated article while maintaining its core message and source citations.

ORIGINAL ARTICLE:
Title: {original_title}
Current Categories: {categories_str}
Content:
{original_content}

ORIGINAL SOURCE (use this to verify every claim in the article):
Title: {original_article.title}
Source: {original_article.source}
URL: {original_article.url}
Original Tags from Source: {tags_str}
Summary: {original_article.summary or "N/A"}
Source Content: {(original_article.content or "N/A")[:2000]}

EDITING GUIDELINES — MUST-DO (non-negotiable):
1. Fix any grammar, spelling, or punctuation errors
2. CRITICAL: The article MUST include a source citation at the end (e.g., "Source: <a href='{original_article.url}'...>")
3. CRITICAL: Do NOT remove or modify source citations and links — they must remain intact
4. Preserve the HTML formatting exactly
5. Do NOT change factual information
6. DO NOT remove or modify the AI disclosure notice. It looks like this:
   <div class="ai-disclosure" ...><em>This article was generated by AI and cites original sources.</em></div>
7. DETECT and REMOVE all subjective praise, opinions, and bias
8. Replace opinion-laden phrases with neutral, factual alternatives
9. Remove these subjective adjectives: visionary, innovative, groundbreaking, revolutionary, game-changing, ambitious, bold, daring, legendary, iconic
10. Use factual descriptors only (e.g., "CEO" NOT "visionary CEO", "announced" NOT "boldly announced")

SOURCE FIDELITY CHECK (non-negotiable):
11. Cross-check the article against the ORIGINAL SOURCE above. Every claim, statistic, quote, company name, and date in the article must appear in or follow directly from the source material.
12. REMOVE or flag any claims that cannot be verified against the source content. If the author added context about competitors or industry trends, verify it is grounded in what the source states — remove anything that appears fabricated or unsupported.
13. If the article includes implications or analysis, ensure they use hedging language ("this could," "this suggests") rather than stating speculation as fact. Rewrite any that don't.

STRUCTURE CHECK (non-negotiable):
14. The article MUST use <h3> subheadings to break content into sections. If subheadings are missing, add appropriate ones (e.g., "The News", "Context", "What This Means", "Looking Ahead").
15. The article should open with a strong lede paragraph before the first subheading. If it doesn't, restructure accordingly.

EDITING GUIDELINES — NICE-TO-HAVE:
16. Improve clarity and readability
17. Ensure professional tone appropriate for tech journalism
18. Preserve the article's section structure, including any <h3> subheadings — do NOT flatten sections into a single block of text
19. Ensure the article flows naturally
20. Make the title more engaging if needed (but keep it neutral)
25. CATEGORY VALIDATION: Review if the current category is appropriate. If the article is clearly about a different category, suggest a correction.

Examples of bias removal:
❌ BIASED: "Elon Musk, the visionary CEO of Tesla, has set an ambitious goal..."
✅ NEUTRAL: "Elon Musk, CEO of Tesla, announced plans to..."

❌ BIASED: "Apple's groundbreaking new AI features..."
✅ NEUTRAL: "Apple's new AI features..."

❌ BIASED: "In a bold move, Microsoft is revolutionizing..."
✅ NEUTRAL: "Microsoft introduced..."

AVAILABLE CATEGORIES:
- Startup (startups, funding, venture capital, entrepreneurship, new companies)
- Hardware (devices, chips, semiconductors, physical products, manufacturing)
- AI (artificial intelligence, machine learning, LLMs, neural networks, computer vision)
- Enterprise (business software, SaaS, enterprise technology, B2B tools, cloud services)
- Mobile & Apps (smartphones, mobile apps, iOS, Android, app stores, mobile gaming)
- Gaming (video games, game consoles, esports, game development, gaming platforms)
- Security & Privacy (cybersecurity, data privacy, hacking, encryption, data breaches)
- Consumer Tech (consumer electronics, smart home, wearables, IoT for consumers)
- General (tech policy, industry trends, regulations, tech culture, other tech news)

Please provide your edited version in the following JSON format:

If categories ARE correct:
{{
    "edited_title": "your improved title here",
    "edited_content": "your improved article content with HTML formatting (MUST include source citation at the end)",
    "edit_summary": "brief summary of changes you made",
    "category_correct": true,
    "corrected_categories": null,
    "category_reason": null
}}

If categories should be CHANGED:
{{
    "edited_title": "your improved title here",
    "edited_content": "your improved article content with HTML formatting (MUST include source citation at the end)",
    "edit_summary": "brief summary of changes you made",
    "category_correct": false,
    "corrected_categories": ["Primary Category", "Optional Secondary"],
    "category_reason": "brief explanation why categories were changed"
}}

IMPORTANT: If the original article is missing a source citation, you MUST add it at the end in this format:
<p><strong>Source:</strong> <a href="{original_article.url}" target="_blank">{original_article.source}</a></p>

If the article is already excellent and needs no changes, still provide the JSON with the original content and note "No changes needed" in the edit_summary.
"""

        try:
            logger.debug(f"Proofreading article: {original_title}")

            response_text = await self._call_llm(
                user_prompt=prompt,
                system_prompt=SYSTEM_PROMPT,
                json_output=True,
            )

            result = self._parse_json_response(response_text)

            edited_title = result.get("edited_title", original_title)
            edited_content = result.get("edited_content", original_content)
            edit_summary = result.get("edit_summary", "Proofreading completed")

            # Handle category correction
            category_correct = result.get("category_correct", True)
            corrected_categories = None
            category_correction_reason = None

            if not category_correct:
                raw_corrected = result.get("corrected_categories") or result.get(
                    "corrected_category"
                )
                category_reason = result.get(
                    "category_reason", "Category reassessed by editor"
                )

                # Normalize to list
                if isinstance(raw_corrected, str):
                    raw_corrected = [raw_corrected]

                if raw_corrected:
                    corrected_categories = [
                        str(cat).strip() for cat in raw_corrected if cat
                    ]
                    if corrected_categories:
                        category_correction_reason = category_reason
                        logger.warning(
                            f"Categories corrected: '{categories_str}' → "
                            f"'{corrected_categories}' (Reason: {category_reason})"
                        )
                    else:
                        corrected_categories = None

            if edited_title != original_title:
                logger.info(f"Title changed: '{original_title}' → '{edited_title}'")

            # Log word count
            text_only = re.sub(r"<[^>]+>", " ", edited_content)
            word_count = len(text_only.split())
            if word_count < self.target_words * 0.85:
                logger.warning(
                    f"Article under target word count: {word_count}/{self.target_words} words"
                )
            elif word_count > self.target_words * 1.15:
                logger.warning(
                    f"Article over target word count: {word_count}/{self.target_words} words"
                )
            else:
                logger.info(f"Word count: {word_count} (target: {self.target_words})")

            logger.info(f"Proofreading complete for: {edited_title}")
            logger.debug(f"Edit summary: {edit_summary}")

            return EditedArticle(
                generated=generated,
                edited_title=edited_title,
                edited_content=edited_content,
                edit_summary=edit_summary,
                editor_model=self.model,
                edited_at=datetime.now(timezone.utc),
                corrected_categories=corrected_categories,
                category_correction_reason=category_correction_reason,
            )

        except Exception as e:
            if "JSONDecodeError" in type(e).__name__:
                logger.error(f"Failed to parse response as JSON: {e}")
                return EditedArticle(
                    generated=generated,
                    edited_title=original_title,
                    edited_content=original_content,
                    edit_summary=f"Proofreading failed (JSON parse error): {str(e)}",
                    editor_model=self.model,
                )
            logger.error(f"Proofreading failed for '{original_title}': {e}")
            raise
