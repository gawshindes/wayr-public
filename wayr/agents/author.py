"""Author Agent — generates AI-powered articles.

The prompt asks the model to emit only <title> and <article> tags. The fallback
in _extract_article_body still strips legacy reasoning tags (analysis/planning/
draft/review) as defense-in-depth in case a model ignores the format instruction.
Source citation is appended by Python post-processing (not by the prompt) when
`add_source_citation` is enabled.
"""

import re
from datetime import datetime, timezone
from typing import List

from wayr.agents.base import BaseAgent
from wayr.models import ClassifiedArticle, GeneratedArticle
from wayr.utils import get_logger

logger = get_logger(__name__)


class AuthorAgent(BaseAgent):
    """Agent responsible for generating AI-powered articles."""

    def __init__(
        self,
        api_key: str,
        model: str,
        provider: str = "openai",
        temperature: float = 0.7,
        max_tokens: int = 2500,
        ai_disclosure: str = "This article was generated by AI and cites original sources.",
        add_source_citation: bool = True,
    ):
        super().__init__(
            name="AuthorAgent",
            provider=provider,
            model=model,
            api_key=api_key,
            temperature=temperature,
            max_tokens=max_tokens,
        )
        self.ai_disclosure = ai_disclosure
        self.add_source_citation = add_source_citation
        logger.info(
            f"AuthorAgent initialized: add_source_citation={add_source_citation}"
        )

    async def generate_articles(
        self, classified_articles: List[ClassifiedArticle]
    ) -> List[GeneratedArticle]:
        """Generate articles from classified articles."""
        logger.info(f"Generating articles for {len(classified_articles)} items...")

        generated = []
        for classified in classified_articles:
            try:
                result = await self._generate_single(classified)
                if result:
                    generated.append(result)
            except Exception as e:
                logger.error(
                    f"Error generating article for '{classified.original.title}': {e}"
                )
                continue

        logger.info(f"Successfully generated {len(generated)} articles")
        return generated

    def _build_source_news(self, classified: ClassifiedArticle) -> str:
        article = classified.original
        parts = [
            f"Title: {article.title}",
            f"Source: {article.source}",
            f"URL: {article.url}",
            f"Published: {article.published_date.strftime('%Y-%m-%d')}",
        ]
        if classified.categories:
            parts.append(f"Categories: {', '.join(classified.categories)}")
        if article.summary:
            parts.append(f"\nSummary: {article.summary}")
        if article.content:
            parts.append(f"\nFull Content:\n{article.content}")
        return "\n".join(parts)

    def _extract_article_body(self, response: str) -> str:
        """Pull the <article>...</article> block; fall back to stripping other tags."""
        body = self._extract_tag(response, "article")
        if body:
            return body

        logger.warning(
            "AuthorAgent: no <article> tag in response; falling back to stripped response"
        )
        # Strip the reasoning tags, keep whatever's left
        stripped = response
        for tag in ("analysis", "planning", "draft", "review", "title"):
            stripped = re.sub(
                rf"<{tag}>.*?</{tag}>",
                "",
                stripped,
                flags=re.DOTALL | re.IGNORECASE,
            )
        return stripped.strip()

    def _extract_title(self, response: str, fallback: str) -> str:
        title = self._extract_tag(response, "title")
        if title:
            # Strip wrapping quotes if the model added them
            return title.strip().strip('"').strip("'")
        logger.warning("AuthorAgent: no <title> tag in response; using source title")
        return fallback

    def _ensure_html(self, body: str) -> str:
        """Wrap plain-text paragraphs in <p> tags if the body isn't already HTML."""
        if "<p" in body.lower() or "<h" in body.lower():
            return body
        paragraphs = [p.strip() for p in re.split(r"\n\s*\n", body) if p.strip()]
        return "\n".join(f"<p>{p}</p>" for p in paragraphs)

    def _append_source_citation(
        self, content: str, classified: ClassifiedArticle
    ) -> str:
        """Append a deterministic source citation block if enabled."""
        if not self.add_source_citation:
            return content
        article = classified.original
        citation = (
            f'<p class="source-citation"><strong>Source:</strong> '
            f'<a href="{article.url}" target="_blank">{article.source}</a></p>'
        )
        return content.rstrip() + "\n" + citation

    def _append_disclosure(self, content: str) -> str:
        disclosure = f'<div class="ai-disclosure"><em>{self.ai_disclosure}</em></div>'
        return content.rstrip() + "\n" + disclosure

    async def _generate_single(self, classified: ClassifiedArticle) -> GeneratedArticle:
        article = classified.original
        source_news = self._build_source_news(classified)

        prompt = self.load_prompt(
            "author",
            SOURCE_NEWS=source_news,
        )

        logger.debug(f"Generating article for: {article.title}")
        response = await self._call_llm(user_prompt=prompt)

        title = self._extract_title(response, fallback=article.title)
        body = self._extract_article_body(response)
        body = self._ensure_html(body)
        body = self._append_source_citation(body, classified)
        body = self._append_disclosure(body)

        text_only = re.sub(r"<[^>]+>", " ", body)
        word_count = len(text_only.split())
        logger.info(f"Generated article: '{title}' ({word_count} words)")

        return GeneratedArticle(
            classified=classified,
            generated_title=title,
            generated_content=body,
            sources_cited=[str(article.url)],
            generated_at=datetime.now(timezone.utc),
            model_used=self.model,
        )
