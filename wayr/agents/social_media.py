    async def _post_to_linkedin(
        self,
        published_articles: List[PublishedArticle],
        summaries: dict | None = None,
    ) -> dict:
        """
        Post articles to LinkedIn Company Page using Community Management API.

        API docs: https://learn.microsoft.com/en-us/linkedin/marketing/community-management/shares/posts-api

        Args:
            published_articles: List of published articles

        Returns:
            Dictionary with LinkedIn posting results
        """
        import json
        from pathlib import Path
        from datetime import datetime, timezone

        results = {
            "posted": 0,
            "failed": 0,
            "skipped": 0,
        }

        # Load tracking file
        tracking_path = self.linkedin_tracking_file
        if tracking_path.startswith("/data/") and not os.path.exists("/data"):
            tracking_path = tracking_path.replace("/data/", "data/")

        tracking_file = Path(tracking_path)
        tracking_file.parent.mkdir(exist_ok=True)

        if tracking_file.exists():
            try:
                posted = json.loads(tracking_file.read_text())
                logger.info(
                    f"LinkedIn: Loaded tracking file: {len(posted)} articles already posted"
                )
            except Exception as e:
                logger.warning(f"LinkedIn: Could not load tracking file: {e}")
                posted = {}
        else:
            logger.info("LinkedIn: No tracking file found, starting fresh")
            posted = {}

        # Post each article
        for article in published_articles:
            article_url = article.wordpress_url
            title = article.edited.edited_title

            article_url_str = str(article_url)
            if article_url_str in posted:
                logger.info(f"  - LinkedIn: Already posted: {title[:50]}...")
                results["skipped"] += 1
                continue

            logger.info(f"  - LinkedIn: Posting: {title[:50]}...")

            try:
                # Use pre-generated base summary (full structured version for LinkedIn)
                base_summary = (summaries or {}).get(article_url_str, "")

                # Format LinkedIn post with full structured summary
                commentary = self._format_linkedin_post(title, base_summary)

                # Get article description for link card
                import html
                import re

                content = article.edited.edited_content
                clean_text = re.sub(r"<[^>]+>", "", content)
                clean_text = html.unescape(clean_text)
                paragraphs = [p.strip() for p in clean_text.split("\n\n") if p.strip()]
                description = paragraphs[0][:200] if paragraphs else ""

                # Post to LinkedIn
                linkedin_result = await self._post_linkedin_article(
                    commentary=commentary,
                    article_url=article_url_str,
                    article_title=title,
                    article_description=description,
                )

                if linkedin_result.get("success"):
                    posted[article_url_str] = {
                        "posted_at": datetime.now(timezone.utc).isoformat(),
                        "title": title,
                        "linkedin_urn": linkedin_result.get("urn"),
                    }
                    results["posted"] += 1
                    logger.info(
                        f"    ✓ LinkedIn: Posted (URN: {linkedin_result.get('urn')})"
                    )
                else:
                    results["failed"] += 1
                    logger.error(
                        f"    ✗ LinkedIn: Failed: {linkedin_result.get('error')}"
                    )

            except Exception as e:
                results["failed"] += 1
                logger.error(f"    ✗ LinkedIn: Error: {e}")
                continue

        # Save tracking file
        try:
            tracking_file.write_text(json.dumps(posted, indent=2))
            logger.info(f"LinkedIn: Saved tracking ({len(posted)} total)")
        except Exception as e:
            logger.warning(f"LinkedIn: Could not save tracking file: {e}")

        return results

    def _format_linkedin_post(
        self,
        title: str,
        summary: str,
    ) -> str:
        """
        Format a LinkedIn post commentary.

        The article title is NOT included here because the LinkedIn article
        link card already displays it. This avoids repetition.

        Args:
            title: Article title (unused — shown in link card)
            summary: Article summary from LLM

        Returns:
            Formatted LinkedIn commentary text
        """
        import html

        summary = html.unescape(summary)

        if summary:
            commentary = summary
        else:
            # Fallback: use title if no summary
            title = html.unescape(title)
            commentary = title

        return commentary

    async def _post_linkedin_article(
        self,
        commentary: str,
        article_url: str,
        article_title: str,
        article_description: str = "",
    ) -> dict:
        """
        Post an article to LinkedIn Company Page using Community Management API.

        API: POST https://api.linkedin.com/rest/posts
        Docs: https://learn.microsoft.com/en-us/linkedin/marketing/community-management/shares/posts-api

        Args:
            commentary: Post text content
            article_url: URL of the article to share
            article_title: Title for the article link card
            article_description: Description for the article link card

        Returns:
            Dict with success status and post URN or error message
        """
        import requests

        api_url = "https://api.linkedin.com/rest/posts"

        post_data = {
            "author": self.linkedin_organization_urn,
            "commentary": commentary,
            "visibility": "PUBLIC",
            "distribution": {
                "feedDistribution": "MAIN_FEED",
                "targetEntities": [],
                "thirdPartyDistributionChannels": [],
            },
            "content": {
                "article": {
                    "source": article_url,
                    "title": article_title,
                    "description": (
                        article_description[:200] if article_description else ""
                    ),
                }
            },
            "lifecycleState": "PUBLISHED",
            "isReshareDisabledByAuthor": False,
        }

        headers = {
            "Authorization": f"Bearer {self.linkedin_access_token}",
            "Content-Type": "application/json",
            "X-Restli-Protocol-Version": "2.0.0",
            "Linkedin-Version": self.LINKEDIN_API_VERSION,
        }

        try:
            response = requests.post(
                api_url, json=post_data, headers=headers, timeout=30
            )

            if response.status_code == 201:
                urn = response.headers.get("x-restli-id", "unknown")
                return {"success": True, "urn": urn}

            # Auto-refresh on 401 (expired token)
            if response.status_code == 401 and self.linkedin_refresh_token:
                logger.info("LinkedIn token expired, attempting auto-refresh...")
                refreshed = self._refresh_linkedin_token()
                if refreshed:
                    # Retry with new token
                    headers["Authorization"] = f"Bearer {self.linkedin_access_token}"
                    response = requests.post(
                        api_url, json=post_data, headers=headers, timeout=30
                    )
                    if response.status_code == 201:
                        urn = response.headers.get("x-restli-id", "unknown")
                        return {"success": True, "urn": urn}

            error_data = response.json() if response.text else {}
            error_msg = error_data.get("message", response.text)
            return {
                "success": False,
                "error": f"HTTP {response.status_code}: {error_msg}",
                "response": error_data,
            }

        except Exception as e:
            return {"success": False, "error": str(e)}

    def _refresh_linkedin_token(self) -> bool:
        """
        Refresh the LinkedIn access token using the refresh token.

        Returns:
            True if refresh succeeded, False otherwise
        """
        import requests

        if not all(
            [
                self.linkedin_refresh_token,
                self.linkedin_client_id,
                self.linkedin_client_secret,
            ]
        ):
            logger.warning(
                "Cannot refresh token: missing refresh_token, client_id, or client_secret"
            )
            return False

        try:
            token_url = "https://www.linkedin.com/oauth/v2/accessToken"
            data = {
                "grant_type": "refresh_token",
                "refresh_token": self.linkedin_refresh_token,
                "client_id": self.linkedin_client_id,
                "client_secret": self.linkedin_client_secret,
            }

            response = requests.post(token_url, data=data, timeout=30)

            if response.status_code == 200:
                token_data = response.json()
                self.linkedin_access_token = token_data["access_token"]
                new_refresh = token_data.get("refresh_token")
                if new_refresh:
                    self.linkedin_refresh_token = new_refresh
                expires_in = token_data.get("expires_in", 0)
                logger.info(
                    f"✓ LinkedIn token refreshed (expires in {expires_in/86400:.0f} days)"
                )
                return True
            else:
                logger.error(
                    f"✗ Token refresh failed: HTTP {response.status_code} - {response.text}"
                )
                return False

        except Exception as e:
            logger.error(f"✗ Token refresh error: {e}")
            return False
