"""
Social Media Agent - Posts published articles to social platforms.

This agent integrates into the WAYR pipeline after the Publishing Agent.
It receives published articles and posts them to Twitter/X and LinkedIn.

Key features:
- Posts to Twitter using Twitter API v2 (OAuth 1.0a)
- Fetches article content to create fresh summaries
- Smart tweet formatting with word boundary truncation
- Rate limit handling (17 tweets/day for Free tier)
- Deduplication tracking to avoid duplicate posts
- Supports multiple social platforms (Twitter, LinkedIn future)
"""

import os
from pathlib import Path
from typing import List, Optional
from wayr.models import PublishedArticle
from wayr.utils import get_logger

logger = get_logger(__name__)


class SocialMediaAgent:
    """
    Agent for posting published articles to social media platforms.

    Integrates into the pipeline after Publisher agent:
    Discovery → Classification → Author → Proofreader → Publisher → **Social Media**
    """

    # LinkedIn Community Management API version (YYYYMM format)
    LINKEDIN_API_VERSION = "202604"

    def __init__(
        self,
        twitter_api_key: Optional[str] = None,
        twitter_api_secret: Optional[str] = None,
        twitter_access_token: Optional[str] = None,
        twitter_access_token_secret: Optional[str] = None,
        linkedin_access_token: Optional[str] = None,
        linkedin_refresh_token: Optional[str] = None,
        linkedin_client_id: Optional[str] = None,
        linkedin_client_secret: Optional[str] = None,
        linkedin_organization_urn: Optional[str] = None,
        tracking_file: str = "/data/twitter_posted.json",
        linkedin_tracking_file: str = "/data/linkedin_posted.json",
    ):
        """
        Initialize the Social Media Agent.

        Summaries are pre-generated by SummaryAgent and available on
        article.edited.summary — no LLM calls needed here.

        Args:
            twitter_api_key: Twitter API key (Consumer Key)
            twitter_api_secret: Twitter API secret (Consumer Secret)
            twitter_access_token: Twitter access token
            twitter_access_token_secret: Twitter access token secret
            linkedin_access_token: LinkedIn OAuth access token
            linkedin_refresh_token: LinkedIn OAuth refresh token (for auto-renewal)
            linkedin_client_id: LinkedIn app client ID (needed for refresh)
            linkedin_client_secret: LinkedIn app client secret (needed for refresh)
            linkedin_organization_urn: LinkedIn Organization URN (urn:li:organization:ID)
            tracking_file: Path to JSON file for tracking Twitter posted articles
            linkedin_tracking_file: Path to JSON file for tracking LinkedIn posted articles
        """
        self.twitter_api_key = twitter_api_key
        self.twitter_api_secret = twitter_api_secret
        self.twitter_access_token = twitter_access_token
        self.twitter_access_token_secret = twitter_access_token_secret
        self.linkedin_access_token = linkedin_access_token
        self.linkedin_refresh_token = linkedin_refresh_token
        self.linkedin_client_id = linkedin_client_id
        self.linkedin_client_secret = linkedin_client_secret
        self.linkedin_organization_urn = linkedin_organization_urn
        self.tracking_file = tracking_file
        self.linkedin_tracking_file = linkedin_tracking_file

        # Check if Twitter credentials are available
        self.twitter_enabled = all(
            [
                twitter_api_key,
                twitter_api_secret,
                twitter_access_token,
                twitter_access_token_secret,
            ]
        )

        if self.twitter_enabled:
            logger.info("✓ Twitter posting enabled")
        else:
            logger.warning("⚠️  Twitter credentials not found - posting disabled")

        # Check if LinkedIn credentials are available
        self.linkedin_enabled = all(
            [
                linkedin_access_token,
                linkedin_organization_urn,
            ]
        )

        if self.linkedin_enabled:
            logger.info(f"✓ LinkedIn posting enabled ({linkedin_organization_urn})")
            if linkedin_refresh_token and linkedin_client_id and linkedin_client_secret:
                logger.info("  ✓ Auto-refresh enabled (refresh token available)")
            else:
                logger.info(
                    "  ⚠️  No refresh token — token must be renewed manually every 60 days"
                )
        else:
            logger.warning("⚠️  LinkedIn credentials not found - posting disabled")

    async def post_to_social_media(
        self, published_articles: List[PublishedArticle]
    ) -> dict:
        """
        Post published articles to all configured social media platforms.

        Generates ONE base summary per article (single LLM call), then reuses
        it for both Twitter and LinkedIn to save tokens.

        Args:
            published_articles: List of articles that were just published to WordPress

        Returns:
            Dictionary with posting results
        """
        results = {
            "twitter": {
                "posted": 0,
                "failed": 0,
                "skipped": 0,
            },
            "linkedin": {
                "posted": 0,
                "failed": 0,
                "skipped": 0,
            },
        }

        if not published_articles:
            logger.info("No articles to post to social media")
            return results

        logger.info(f"Posting {len(published_articles)} articles to social media...")

        # Read pre-generated summaries from EditedArticle (set by SummaryAgent)
        summaries = {}
        for article in published_articles:
            article_url_str = str(article.wordpress_url)
            summaries[article_url_str] = article.edited.summary or ""

        # Post to Twitter
        if self.twitter_enabled:
            twitter_results = await self._post_to_twitter(published_articles, summaries)
            results["twitter"] = twitter_results
        else:
            logger.info("Twitter posting disabled (no credentials)")
            results["twitter"]["skipped"] = len(published_articles)

        # Post to LinkedIn Company Page
        if self.linkedin_enabled:
            linkedin_results = await self._post_to_linkedin(
                published_articles, summaries
            )
            results["linkedin"] = linkedin_results
        else:
            logger.info("LinkedIn posting disabled (no credentials)")
            results["linkedin"]["skipped"] = len(published_articles)

        return results

    # ---- one link (the daily digest post), both platforms ----

    def _tracking_path(self, path: str) -> Path:
        if path.startswith("/data/") and not os.path.exists("/data"):
            path = path.replace("/data/", "data/")  # local run
        p = Path(path)
        p.parent.mkdir(parents=True, exist_ok=True)
        return p

    @staticmethod
    def _load_tracking(path: Path) -> dict:
        import json

        if not path.exists():
            return {}
        try:
            data = json.loads(path.read_text())
            return data if isinstance(data, dict) else {}
        except Exception as e:  # noqa: BLE001
            logger.warning(f"Could not load tracking file {path}: {e}")
            return {}

    @staticmethod
    def _save_tracking(path: Path, posted: dict) -> None:
        import json

        try:
            path.write_text(json.dumps(posted, indent=2))
        except Exception as e:  # noqa: BLE001
            logger.warning(f"Could not save tracking file {path}: {e}")

    async def post_link(
        self,
        url: str,
        title: str,
        linkedin_text: str,
        tweet_text: str,
        description: str = "",
    ) -> dict:
        """Post one URL — the newsletter issue — to every configured platform.

        Same tracking files as the per-article path, keyed by URL, so a re-run of
        the same issue is skipped rather than posted twice. Returns
        {"twitter": {...}, "linkedin": {...}} with posted/failed/skipped counts,
        and each platform's id when it posted.
        """
        from datetime import datetime, timezone

        results: dict = {
            "twitter": {"posted": 0, "failed": 0, "skipped": 0},
            "linkedin": {"posted": 0, "failed": 0, "skipped": 0},
        }
        now = datetime.now(timezone.utc).isoformat()

        if self.twitter_enabled:
            path = self._tracking_path(self.tracking_file)
            posted = self._load_tracking(path)
            if url in posted:
                results["twitter"]["skipped"] = 1
                logger.info("Twitter: already posted this issue; skipped")
            else:
                try:
                    r = await self._post_tweet(
                        self._format_tweet(title, tweet_text, url)
                    )
                except Exception as e:  # noqa: BLE001
                    r = {"success": False, "error": str(e)}
                if r.get("success"):
                    posted[url] = {
                        "posted_at": now,
                        "title": title,
                        "tweet_id": r.get("tweet_id"),
                    }
                    self._save_tracking(path, posted)
                    results["twitter"]["posted"] = 1
                    results["twitter"]["id"] = r.get("tweet_id")
                    logger.info(f"Twitter: posted the issue ({r.get('tweet_id')})")
                else:
                    results["twitter"]["failed"] = 1
                    results["twitter"]["error"] = r.get("error")
                    logger.error(f"Twitter: failed: {r.get('error')}")
        else:
            results["twitter"]["skipped"] = 1

        if self.linkedin_enabled:
            path = self._tracking_path(self.linkedin_tracking_file)
            posted = self._load_tracking(path)
            if url in posted:
                results["linkedin"]["skipped"] = 1
                logger.info("LinkedIn: already posted this issue; skipped")
            else:
                try:
                    r = await self._post_linkedin_article(
                        commentary=linkedin_text,
                        article_url=url,
                        article_title=title,
                        article_description=description,
                    )
                except Exception as e:  # noqa: BLE001
                    r = {"success": False, "error": str(e)}
                if r.get("success"):
                    posted[url] = {
                        "posted_at": now,
                        "title": title,
                        "linkedin_urn": r.get("urn"),
                    }
                    self._save_tracking(path, posted)
                    results["linkedin"]["posted"] = 1
                    results["linkedin"]["id"] = r.get("urn")
                    logger.info(f"LinkedIn: posted the issue ({r.get('urn')})")
                else:
                    results["linkedin"]["failed"] = 1
                    results["linkedin"]["error"] = r.get("error")
                    logger.error(f"LinkedIn: failed: {r.get('error')}")
        else:
            results["linkedin"]["skipped"] = 1

        return results

    async def _post_to_twitter(
        self,
        published_articles: List[PublishedArticle],
        summaries: dict | None = None,
    ) -> dict:
        """
        Post articles to Twitter using Twitter API v2.

        Args:
            published_articles: List of published articles

        Returns:
            Dictionary with Twitter posting results
        """
        import json
        from pathlib import Path
        from datetime import datetime, timedelta, timezone

        results = {
            "posted": 0,
            "failed": 0,
            "skipped": 0,
        }

        # Load tracking file
        # Handle both Modal (/data/) and local (data/) paths
        tracking_path = self.tracking_file
        if tracking_path.startswith("/data/") and not os.path.exists("/data"):
            # Local development - use relative path
            tracking_path = tracking_path.replace("/data/", "data/")

        tracking_file = Path(tracking_path)
        tracking_file.parent.mkdir(exist_ok=True)

        if tracking_file.exists():
            try:
                posted = json.loads(tracking_file.read_text())
                logger.info(
                    f"Loaded tracking file: {len(posted)} articles already posted"
                )
            except Exception as e:
                logger.warning(f"Could not load tracking file: {e}")
                posted = {}
        else:
            logger.info("No tracking file found, starting fresh")
            posted = {}

        # Check rate limit (Twitter Free tier: 17 tweets/day)
        daily_limit = 17
        now = datetime.now(timezone.utc)
        day_ago = now - timedelta(days=1)

        def _parse_utc(iso_str: str) -> datetime:
            dt = datetime.fromisoformat(iso_str)
            return dt if dt.tzinfo else dt.replace(tzinfo=timezone.utc)

        recent_posts = sum(
            1 for v in posted.values() if _parse_utc(v["posted_at"]) > day_ago
        )

        logger.info(f"Posted in last 24h: {recent_posts}/{daily_limit}")

        if recent_posts >= daily_limit:
            logger.warning(f"Daily limit reached ({daily_limit} posts/day)")
            results["skipped"] = len(published_articles)
            return results

        # Post each article
        for article in published_articles:
            article_url = article.wordpress_url
            title = article.edited.edited_title

            # Check if already posted (convert HttpUrl to string for comparison)
            article_url_str = str(article_url)
            if article_url_str in posted:
                logger.info(f"  - Already posted: {title[:50]}...")
                results["skipped"] += 1
                continue

            # Check if we've hit the daily limit
            if results["posted"] + recent_posts >= daily_limit:
                logger.warning(
                    f"Stopping: Would exceed daily limit ({daily_limit} posts/day)"
                )
                results["skipped"] += (
                    len(published_articles) - results["posted"] - results["failed"]
                )
                break

            logger.info(f"  - Posting: {title[:50]}...")

            try:
                # Use pre-generated base summary, extract first sentence for Twitter
                base_summary = (summaries or {}).get(article_url_str, "")
                twitter_summary = self._extract_first_sentence(
                    base_summary, max_chars=150
                )

                # Create tweet text
                tweet_text = self._format_tweet(title, twitter_summary, article_url_str)

                # Post to Twitter
                tweet_result = await self._post_tweet(tweet_text)

                if tweet_result.get("success"):
                    # Mark as posted (use string URL for JSON serialization)
                    posted[article_url_str] = {
                        "posted_at": datetime.now(timezone.utc).isoformat(),
                        "title": title,
                        "tweet_id": tweet_result.get("tweet_id"),
                    }
                    results["posted"] += 1
                    logger.info(
                        f"    ✓ Posted successfully (ID: {tweet_result.get('tweet_id')})"
                    )
                else:
                    results["failed"] += 1
                    logger.error(f"    ✗ Failed to post: {tweet_result.get('error')}")

            except Exception as e:
                results["failed"] += 1
                logger.error(f"    ✗ Error posting: {e}")
                continue

        # Save tracking file
        try:
            tracking_file.write_text(json.dumps(posted, indent=2))
            logger.info(f"✓ Saved tracking file ({len(posted)} total articles tracked)")
        except Exception as e:
            logger.warning(f"Could not save tracking file: {e}")

        return results

    def _extract_first_sentence(self, summary: str, max_chars: int = 150) -> str:
        """
        Extract the first sentence from a base summary for Twitter use.
        No LLM call needed — pure string extraction.

        Args:
            summary: Full base summary text
            max_chars: Maximum character limit

        Returns:
            First sentence, truncated to fit if needed
        """
        import re

        if not summary:
            return ""

        # Get the first line
        first_line = summary.split("\n")[0].strip()

        # Extract first sentence (handle decimals like $5.55 by requiring space after period)
        sentences = re.split(r"(?<=[.!?])\s+(?=[A-Z])", first_line)
        first_sentence = sentences[0].strip() if sentences else first_line

        # Truncate if needed, break at word boundary
        if len(first_sentence) > max_chars:
            first_sentence = first_sentence[:max_chars].rsplit(" ", 1)[0]
            if not first_sentence.endswith((".", "!", "?")):
                first_sentence += "..."

        return first_sentence

    def _format_tweet(self, title: str, summary: str, article_url: str) -> str:
        """
        Format a tweet with summary and URL (no title to avoid duplication).

        Twitter limits:
        - Max 280 characters total
        - URLs auto-shortened to 23 chars (t.co links)
        - Target: ~150 char summary for readability

        Args:
            title: Article title (used as fallback if no summary)
            summary: Article summary
            article_url: WordPress URL

        Returns:
            Formatted tweet text (max 280 chars)
        """
        import html

        # Decode HTML entities
        summary = html.unescape(summary)
        title = html.unescape(title)

        # Twitter auto-shortens URLs to 23 chars (t.co links)
        # Max available for summary: 280 - 23 (url) - 2 (\n\n) = 255 chars
        # Target ~150 chars for readability
        target_summary_length = 150

        # Use summary if available, otherwise use title
        if summary:
            # Truncate summary to target length, break at word boundary
            if len(summary) > target_summary_length:
                summary_text = summary[:target_summary_length].rsplit(" ", 1)[0] + "..."
            else:
                summary_text = summary
        else:
            # Fallback to title if no summary
            if len(title) > target_summary_length:
                summary_text = title[:target_summary_length].rsplit(" ", 1)[0] + "..."
            else:
                summary_text = title

        # Format: summary + URL
        tweet_text = f"{summary_text}\n\n{article_url}"

        return tweet_text

    async def _post_tweet(self, text: str) -> dict:
        """
        Post a tweet using Twitter API v2 with OAuth 1.0a.

        Args:
            text: Tweet text (max 280 characters)

        Returns:
            Dict with success status and tweet ID or error message
        """
        import requests
        from requests_oauthlib import OAuth1

        # Twitter API v2 endpoint
        api_url = "https://api.twitter.com/2/tweets"

        # OAuth 1.0a authentication
        auth = OAuth1(
            self.twitter_api_key,
            self.twitter_api_secret,
            self.twitter_access_token,
            self.twitter_access_token_secret,
        )

        # Tweet payload
        payload = {"text": text}

        try:
            response = requests.post(api_url, auth=auth, json=payload, timeout=30)

            if response.status_code == 201:
                # Success
                response_data = response.json()
                tweet_id = response_data.get("data", {}).get("id", "unknown")
                return {"success": True, "tweet_id": tweet_id}
            else:
                # Error
                error_data = response.json() if response.text else {}
                error_msg = error_data.get(
                    "detail", error_data.get("title", response.text)
                )
                return {
                    "success": False,
                    "error": f"HTTP {response.status_code}: {error_msg}",
                    "response": error_data,
                }

        except Exception as e:
            return {"success": False, "error": str(e)}

