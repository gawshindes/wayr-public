"""Check word counts of recent articles from WordPress."""

import argparse
import re
import sys

import requests

SITES = {
    "india": "https://india.wayrtoday.com",
    "us": "https://wayr.today",
    "staging": "https://staging.wayrtoday.com",
}


def strip_html(html: str) -> str:
    """Strip HTML tags and return plain text."""
    text = re.sub(r"<[^>]+>", " ", html)
    # Collapse whitespace
    text = re.sub(r"\s+", " ", text).strip()
    return text


def fetch_recent_posts(site_url: str, count: int = 20):
    """Fetch recent posts from WordPress REST API."""
    url = f"{site_url}/wp-json/wp/v2/posts"
    params = {
        "per_page": count,
        "orderby": "date",
        "order": "desc",
        "_fields": "id,title,content,date,link",
    }
    resp = requests.get(url, params=params, timeout=30)
    resp.raise_for_status()
    return resp.json()


def main():
    parser = argparse.ArgumentParser(
        description="Check word counts of recent WordPress articles"
    )
    parser.add_argument(
        "site", choices=list(SITES.keys()), help="Site to check: india, us, or staging"
    )
    parser.add_argument(
        "-n",
        "--count",
        type=int,
        default=20,
        help="Number of articles to fetch (default: 20)",
    )
    args = parser.parse_args()

    site_url = SITES[args.site]
    print(f"Fetching last {args.count} articles from {site_url}...\n")

    try:
        posts = fetch_recent_posts(site_url, args.count)
    except requests.exceptions.RequestException as e:
        print(f"Error fetching posts: {e}")
        sys.exit(1)

    if not posts:
        print("No posts found.")
        sys.exit(0)

    word_counts = []
    print(f"{'#':<4} {'Words':<7} {'Date':<12} {'Title'}")
    print("-" * 90)

    for i, post in enumerate(posts, 1):
        title = post["title"]["rendered"]
        content_html = post["content"]["rendered"]
        date = post["date"][:10]

        # Strip HTML and count words
        text = strip_html(content_html)

        # Remove the AI disclosure and source citation for body-only count
        # AI disclosure pattern
        text = re.sub(
            r"This article was generated by AI and cites original sources\.?", "", text
        )
        # Source citation pattern
        text = re.sub(r"Source:\s*\S+.*$", "", text)

        word_count = len(text.split())
        word_counts.append(word_count)

        # Truncate title for display
        display_title = title[:60] + "..." if len(title) > 60 else title
        print(f"{i:<4} {word_count:<7} {date:<12} {display_title}")

    print("-" * 90)
    avg = sum(word_counts) / len(word_counts)
    min_wc = min(word_counts)
    max_wc = max(word_counts)
    under_700 = sum(1 for wc in word_counts if wc < 700)
    over_900 = sum(1 for wc in word_counts if wc > 900)

    print(f"\nArticles: {len(word_counts)}")
    print(f"Avg: {avg:.0f} | Min: {min_wc} | Max: {max_wc}")
    print(f"Under 700: {under_700} | Over 900: {over_900}")


if __name__ == "__main__":
    main()
