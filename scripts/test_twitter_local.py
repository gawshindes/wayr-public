"""
Local test script for Twitter poster.

This script tests the Twitter API integration locally before deploying to Modal.

Usage:
  python scripts/test_twitter_local.py
"""

import os
import sys
import json
import html
from pathlib import Path
from datetime import datetime
from dotenv import load_dotenv

# Add parent directory to path to import from scripts
sys.path.insert(0, str(Path(__file__).parent))

# Import the post_tweet function from twitter_poster
from twitter_poster import post_tweet


def main():
    """Test Twitter posting locally."""
    # Load .env file
    load_dotenv()

    print("=" * 60)
    print("Twitter Poster - Local Test")
    print("=" * 60)

    # Load environment variables
    wordpress_url = os.environ.get("WORDPRESS_URL", "https://wayr.today")
    api_key = os.environ.get("TWITTER_API_KEY")
    api_secret = os.environ.get("TWITTER_API_SECRET")
    access_token = os.environ.get("TWITTER_ACCESS_TOKEN")
    access_token_secret = os.environ.get("TWITTER_ACCESS_TOKEN_SECRET")

    # Validate credentials
    if not all([api_key, api_secret, access_token, access_token_secret]):
        print("\n❌ ERROR: Twitter API credentials not set in .env file")
        print("\nRequired environment variables:")
        print("  - TWITTER_API_KEY")
        print("  - TWITTER_API_SECRET")
        print("  - TWITTER_ACCESS_TOKEN")
        print("  - TWITTER_ACCESS_TOKEN_SECRET")
        print("\nPlease add these to your .env file and try again.")
        sys.exit(1)

    print(f"\n✓ Twitter API credentials loaded from .env")
    print(f"✓ WordPress URL: {wordpress_url}")

    # Use local tracking file for testing
    tracking_file = Path("data/twitter_posted_test.json")
    tracking_file.parent.mkdir(exist_ok=True)

    if tracking_file.exists():
        try:
            posted = json.loads(tracking_file.read_text())
            print(f"✓ Loaded tracking file: {len(posted)} articles already posted")
        except Exception as e:
            print(f"⚠️  Warning: Could not load tracking file: {e}")
            posted = {}
    else:
        print("✓ No tracking file found, starting fresh")
        posted = {}

    # Fetch RSS feed
    print(f"\n{'='*60}")
    print("Fetching RSS feed...")
    print("=" * 60)

    import feedparser

    rss_url = f"{wordpress_url.rstrip('/')}/feed/"
    print(f"URL: {rss_url}")

    try:
        feed = feedparser.parse(rss_url)
    except Exception as e:
        print(f"\n❌ ERROR: Failed to fetch RSS feed: {e}")
        sys.exit(1)

    if not feed.entries:
        print("\n⚠️  No articles found in RSS feed")
        sys.exit(0)

    print(f"✓ Found {len(feed.entries)} articles in RSS feed\n")

    # Show first article for testing
    entry = feed.entries[0]
    article_url = entry.link
    title = html.unescape(entry.title)

    # Fetch article content to create a fresh summary
    print(f"\nFetching article content...")
    import requests
    from bs4 import BeautifulSoup

    summary = ""
    try:
        # Fetch the article page
        response = requests.get(article_url, timeout=10)
        response.raise_for_status()

        # Parse HTML and extract article content
        soup = BeautifulSoup(response.text, "html.parser")

        # Try to find article content (common selectors for WordPress)
        article_content = None
        for selector in [
            "article .entry-content",
            "article",
            ".post-content",
            ".content",
        ]:
            article_content = soup.select_one(selector)
            if article_content:
                break

        if article_content:
            # Get first paragraph that's not the AI disclosure
            paragraphs = article_content.find_all("p")
            for p in paragraphs:
                text = p.get_text().strip()
                # Skip AI disclosure and empty paragraphs
                if text and not text.startswith("This article was generated by AI"):
                    summary = text
                    break

        print(f"✓ Extracted summary from article")

    except Exception as e:
        print(f"⚠️  Warning: Could not fetch article content: {e}")
        # Fallback to RSS description if article fetch fails
        summary = html.unescape(entry.get("description", ""))
        if summary.startswith("This article was generated by AI"):
            summary = summary.split(".", 1)[1].strip() if "." in summary else ""
        print(f"✓ Using RSS description as fallback")

    print("=" * 60)
    print("FIRST ARTICLE (for testing):")
    print("=" * 60)
    print(f"Title: {title}")
    print(f"URL: {article_url}")
    print(f"Summary: {summary[:150]}...")

    # Check if already posted
    if article_url in posted:
        print(f"\n⚠️  This article has already been posted to Twitter")
        print(f"   Posted at: {posted[article_url]['posted_at']}")
        print(f"   Tweet ID: {posted[article_url].get('tweet_id', 'unknown')}")

        response = input("\nPost it again anyway? (y/n): ").strip().lower()
        if response != "y":
            print("Cancelled.")
            sys.exit(0)
    else:
        print(f"\n✓ Not yet posted to Twitter")

    # Create tweet text (same logic as twitter_poster.py)
    # Twitter auto-shortens URLs to 23 chars (t.co links)
    url_length = 23
    max_chars = 280

    # Calculate available space for title + summary
    # Account for: title + "\n\n" (2 chars) + "\n\n" (2 chars) + URL (23 chars)
    available_for_text = max_chars - url_length - 4  # 253 chars

    # Create tweet based on available space
    if len(title) <= available_for_text - 30:  # Leave room for summary
        # Title fits, add summary
        remaining = available_for_text - len(title)
        if remaining > 30 and summary:
            # Truncate summary to fit, break at word boundary
            summary_short = summary[: remaining - 3].rsplit(" ", 1)[0] + "..."
            tweet_text = f"{title}\n\n{summary_short}"
        else:
            # Not enough room for summary, just title
            tweet_text = title
    else:
        # Title is too long, truncate at word boundary
        tweet_text = title[: available_for_text - 3].rsplit(" ", 1)[0] + "..."

    # Add URL on a new line
    tweet_text = f"{tweet_text}\n\n{article_url}"

    print(f"\n{'='*60}")
    print("TWEET PREVIEW:")
    print("=" * 60)
    print(tweet_text)
    print(f"\nLength: {len(tweet_text)} characters")

    if len(tweet_text) > 280:
        print(f"⚠️  WARNING: Tweet exceeds 280 characters!")

    # Ask user if they want to post
    print(f"\n{'='*60}")
    response = input("📤 Post this tweet to Twitter? (y/n): ").strip().lower()

    if response != "y":
        print("Cancelled.")
        sys.exit(0)

    # Post to Twitter
    print("\n🐦 Posting to Twitter...")
    try:
        result = post_tweet(
            api_key=api_key,
            api_secret=api_secret,
            access_token=access_token,
            access_token_secret=access_token_secret,
            text=tweet_text,
        )

        if result.get("success"):
            print(f"\n✅ Posted successfully!")
            print(f"   Tweet ID: {result.get('tweet_id')}")
            print(f"   URL: https://twitter.com/user/status/{result.get('tweet_id')}")

            # Mark as posted
            posted[article_url] = {
                "posted_at": datetime.utcnow().isoformat(),
                "title": title,
                "tweet_id": result.get("tweet_id"),
            }

            # Save tracking file
            tracking_file.write_text(json.dumps(posted, indent=2))
            print(f"\n✓ Saved to tracking file: {tracking_file}")

        else:
            print(f"\n❌ Failed to post: {result.get('error')}")
            if result.get("response"):
                print(f"\n   API Response:")
                print(f"   {json.dumps(result.get('response'), indent=2)}")
            sys.exit(1)

    except Exception as e:
        print(f"\n❌ Error posting to Twitter: {e}")
        import traceback

        traceback.print_exc()
        sys.exit(1)

    print("\n" + "=" * 60)
    print("✅ Local test complete!")
    print("=" * 60)


if __name__ == "__main__":
    main()
